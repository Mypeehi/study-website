/**
 * Returns the deterministic official quote for a given date
 * (defaulting to the current date).
 */
export function getOfficialQuoteForDate(date: Date = new Date()): OfficialDailyQuote {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % OFFICIAL_DAILY_QUOTES.length;
  return OFFICIAL_DAILY_QUOTES[index];
}
